"""Integration test for the carts/orders schema migration (task 3.2).

Applies migration ``0002_carts_orders`` (on top of ``0001_initial_schema``) to a
fresh database and asserts that:

  * the new tables (``carts``, ``cart_items``, ``orders``, ``order_items``)
    exist and accept a full valid customer -> cart -> order insert chain;
  * ``UNIQUE(cart_id, product_id)`` enforces combine-on-add (Req 4.5);
  * ``carts.customer_id`` is UNIQUE (one active cart per customer);
  * ``orders.order_number`` is UNIQUE (human-friendly id);
  * the foreign keys reject orphan rows;
  * the ``rejection_reason`` length bound (<=500) and the ``order_state`` enum
    are enforced;
  * the migration upgrades and downgrades cleanly (0002 removes only its own
    tables, leaving the 0001 tables intact), and ``alembic check`` reports no
    drift between ``Base.metadata`` and the migrated database.

As with the initial-schema test, the suite always runs against throwaway
**SQLite** and additionally against **PostgreSQL** when ``MARKETPLACE_TEST_PG_URL``
points at a reachable server. SQLite foreign-key enforcement is explicitly
enabled (it is off by default) so the FK assertions are meaningful.
"""

from __future__ import annotations

import os
import uuid
from pathlib import Path

import pytest
import sqlalchemy as sa
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

pytestmark = pytest.mark.integration

PROJECT_ROOT = Path(__file__).resolve().parents[2]

# Tables introduced by 0002; the 0001 tables must survive a downgrade to 0001.
NEW_TABLES = {"carts", "cart_items", "orders", "order_items"}
INITIAL_TABLES = {"meta", "users", "categories", "products"}


def _alembic_config(db_url: str) -> Config:
    cfg = Config(str(PROJECT_ROOT / "alembic.ini"))
    cfg.set_main_option("script_location", str(PROJECT_ROOT / "migrations"))
    cfg.set_main_option("sqlalchemy.url", db_url)
    return cfg


# ---------------------------------------------------------------------------
# Insert helpers (raw SQL so the test exercises the migrated schema directly).
# ---------------------------------------------------------------------------
def _new_user(conn: sa.Connection, telegram_user_id: int) -> str:
    uid = uuid.uuid4().hex
    conn.execute(
        sa.text(
            "INSERT INTO users (user_id, telegram_user_id, role) "
            "VALUES (:id, :tg, 'CUSTOMER')"
        ),
        {"id": uid, "tg": telegram_user_id},
    )
    return uid


def _new_category(conn: sa.Connection, name: str) -> str:
    cid = uuid.uuid4().hex
    conn.execute(
        sa.text("INSERT INTO categories (category_id, name) VALUES (:id, :name)"),
        {"id": cid, "name": name},
    )
    return cid


def _new_product(conn: sa.Connection, category_id: str) -> str:
    pid = uuid.uuid4().hex
    conn.execute(
        sa.text(
            "INSERT INTO products (product_id, name, category_id, unit, "
            "price_per_unit, min_order_quantity, stock_quantity) "
            "VALUES (:id, 'Cotton Seed Oil Cake', :c, 'KILOGRAM', 100.00, "
            "10.000, 500.000)"
        ),
        {"id": pid, "c": category_id},
    )
    return pid


def _new_cart(conn: sa.Connection, customer_id: str) -> str:
    cart_id = uuid.uuid4().hex
    conn.execute(
        sa.text("INSERT INTO carts (cart_id, customer_id) VALUES (:id, :cust)"),
        {"id": cart_id, "cust": customer_id},
    )
    return cart_id


def _add_cart_item(conn: sa.Connection, cart_id: str, product_id: str, qty="10.000"):
    conn.execute(
        sa.text(
            "INSERT INTO cart_items (cart_item_id, cart_id, product_id, quantity) "
            "VALUES (:id, :cart, :prod, :qty)"
        ),
        {"id": uuid.uuid4().hex, "cart": cart_id, "prod": product_id, "qty": qty},
    )


def _new_order(conn: sa.Connection, customer_id: str, order_number: int, **overrides):
    params = {
        "id": uuid.uuid4().hex,
        "num": order_number,
        "cust": customer_id,
        "state": "PAYMENT_PENDING",
        "total": "1000.00",
        "reason": None,
    }
    params.update(overrides)
    conn.execute(
        sa.text(
            "INSERT INTO orders (order_id, order_number, customer_id, state, "
            "total_amount, rejection_reason) "
            "VALUES (:id, :num, :cust, :state, :total, :reason)"
        ),
        params,
    )
    return params["id"]


def _add_order_item(conn: sa.Connection, order_id: str, product_id: str):
    conn.execute(
        sa.text(
            "INSERT INTO order_items (order_item_id, order_id, product_id, "
            "ordered_quantity, unit_price, line_amount) "
            "VALUES (:id, :order, :prod, 10.000, 100.00, 1000.00)"
        ),
        {"id": uuid.uuid4().hex, "order": order_id, "prod": product_id},
    )


# ---------------------------------------------------------------------------
# Backend fixtures
# ---------------------------------------------------------------------------
def _backends():
    params = [pytest.param("sqlite", id="sqlite")]
    if os.environ.get("MARKETPLACE_TEST_PG_URL"):
        params.append(pytest.param("postgresql", id="postgresql"))
    return params


def _enable_sqlite_fk(engine: sa.Engine) -> None:
    """SQLite does not enforce foreign keys unless asked to per-connection."""

    @sa.event.listens_for(engine, "connect")
    def _set_pragma(dbapi_connection, _record):  # pragma: no cover - trivial
        cursor = dbapi_connection.cursor()
        cursor.execute("PRAGMA foreign_keys=ON")
        cursor.close()


@pytest.fixture(params=_backends())
def db(request, tmp_path, monkeypatch):
    """Apply migrations to a fresh DB; yield (engine, cfg) for the backend."""
    if request.param == "sqlite":
        url = f"sqlite:///{tmp_path / 'carts_orders_test.db'}"
    else:
        url = os.environ["MARKETPLACE_TEST_PG_URL"]

    monkeypatch.setenv("DB_URL", url)
    cfg = _alembic_config(url)

    command.downgrade(cfg, "base")
    command.upgrade(cfg, "head")

    eng = sa.create_engine(url)
    if request.param == "sqlite":
        _enable_sqlite_fk(eng)
    try:
        yield eng, cfg
    finally:
        eng.dispose()
        command.downgrade(cfg, "base")


