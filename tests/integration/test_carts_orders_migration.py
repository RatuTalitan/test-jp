def test_new_tables_exist(db):
    engine, _ = db
    tables = set(sa.inspect(engine).get_table_names())
    assert NEW_TABLES.issubset(tables), tables
    # The initial-schema tables must still be present after 0002.
    assert INITIAL_TABLES.issubset(tables), tables


def test_full_insert_chain_succeeds(db):
    engine, _ = db
    with engine.begin() as conn:
        customer = _new_user(conn, 1001)
        category = _new_category(conn, "Oil Cakes")
        product = _new_product(conn, category)
        cart = _new_cart(conn, customer)
        _add_cart_item(conn, cart, product)
        order = _new_order(conn, customer, order_number=1)
        _add_order_item(conn, order, product)

    with engine.connect() as conn:
        assert conn.execute(sa.text("SELECT count(*) FROM cart_items")).scalar_one() == 1
        assert conn.execute(sa.text("SELECT count(*) FROM order_items")).scalar_one() == 1


