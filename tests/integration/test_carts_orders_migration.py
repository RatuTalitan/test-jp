def test_order_schema_version_defaults_to_one(db):
    engine, _ = db
    with engine.begin() as conn:
        customer = _new_user(conn, 1008)
        order = _new_order(conn, customer, order_number=11)
        version = conn.execute(
            sa.text("SELECT schema_version FROM orders WHERE order_id = :id"),
            {"id": order},
        ).scalar_one()
    assert version == 1


# ---------------------------------------------------------------------------
# Migration round-trip and drift
# ---------------------------------------------------------------------------
def test_downgrade_to_initial_removes_only_new_tables(db):
    engine, cfg = db
    command.downgrade(cfg, "0001_initial_schema")
    tables = set(sa.inspect(engine).get_table_names())
    assert not (NEW_TABLES & tables), tables
    assert INITIAL_TABLES.issubset(tables), tables
    # Restore head so the fixture teardown's downgrade-to-base is consistent.
    command.upgrade(cfg, "head")


def test_alembic_check_reports_no_drift(db):
    engine, cfg = db
    # command.check raises AutogenerateDiffsDetected if Base.metadata and the
    # migrated database disagree; no exception means the migration matches.
    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - failure path
        pytest.fail(f"Schema drift detected between models and migration: {exc}")
