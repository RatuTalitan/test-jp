# Payments (task 3.3; design.md -> Data Models -> Payments).
#
# Exactly one payment per order (UNIQUE ``order_id``). ``utr`` is variable-length
# TEXT (not fixed-width) so the **configurable** UTR pattern (seller_settings,
# task 3.5) can vary in length; it is globally UNIQUE across all orders (Req 6.4)
# but NULLABLE with SQL's "NULLs are distinct" semantics, so the many offline
# orders that never record a UTR can all coexist with a NULL ``utr``. The
# uniqueness is enforced by a dedicated UNIQUE index (``ix_payments_utr``). Only
# the object-storage *key* of an optional screenshot is stored here; the blob
# itself lives in the private bucket, never in the DB (Req 6.3).
# ---------------------------------------------------------------------------
class Payment(Base):
    """Per-order payment record with a globally-unique nullable UTR (Req 6)."""

    __tablename__ = "payments"
    __table_args__ = (
        # Global UTR uniqueness across orders; multiple NULLs allowed (NULLs are
        # distinct on both PostgreSQL and SQLite), so offline orders coexist.
        sa.Index("ix_payments_utr", "utr", unique=True),
    )

    payment_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid, primary_key=True, default=uuid.uuid4
    )
    # One payment per order -> UNIQUE FK to orders (Req 6).
    order_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid, sa.ForeignKey("orders.order_id"), nullable=False, unique=True
    )
    # Variable-length to support the configurable UTR pattern; globally unique
    # via ix_payments_utr; NULL until the customer submits a UTR (Req 6.4).
    utr: Mapped[Optional[str]] = mapped_column(sa.Text, nullable=True)
    utr_submitted_at: Mapped[Optional[datetime]] = mapped_column(
        sa.DateTime(timezone=True), nullable=True
    )
    # Object-storage reference only; the blob never lives in the DB (Req 6.3).
    screenshot_object_key: Mapped[Optional[str]] = mapped_column(sa.Text, nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )


