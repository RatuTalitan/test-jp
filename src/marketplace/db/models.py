from datetime import datetime
from typing import Optional

import sqlalchemy as sa
from sqlalchemy.dialects import postgresql
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# ---------------------------------------------------------------------------
# Constraint/index naming convention.
#
# A deterministic naming convention keeps constraint and index names identical
# between the ORM metadata and the hand-written Alembic migration, and lets
# Alembic autogenerate produce stable names for tasks 3.2 / 3.3 / 3.5.
# ---------------------------------------------------------------------------
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Declarative base carrying the shared, conventionally-named metadata."""

    metadata = sa.MetaData(naming_convention=NAMING_CONVENTION)


