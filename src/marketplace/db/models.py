# Seller_Settings (task 3.5; design.md -> Data Models -> Seller_Settings;
# Req 6.2, 6.6, 19.1, 19.3, 19.5, 19.7).
#
# A SINGLE settings row owned by the Seller holding the operator-configurable
# values that were previously pure environment configuration (pickup location,
# UPI payee details, UPI QR reference, the configurable UTR pattern). Moving
# them here makes them editable at runtime through the Admin_Console (Req 19)
# without a redeploy; environment variables may still *seed* initial defaults.
#
# Singleton: enforced exactly like the ``meta`` table's ``CHECK (meta_id = 1)``
# pattern - a constant discriminator column ``singleton`` pinned to 1 by a CHECK
# and made UNIQUE, so at most one settings row can ever exist regardless of the
# UUID primary key. ``present_instructions`` / the pickup notification therefore
# always read the same authoritative row.
#
# Portability: ``upi_qr_object_key`` stores only an object-storage *reference*;
# the QR blob itself never lives in the DB (Req 19.5/19.6), mirroring
# ``payments.screenshot_object_key``. ``utr_pattern`` is variable-length TEXT
# with a server_default of exactly-12-alphanumeric (Req 6.2/6.6); the VPA in
# ``upi_address`` is validated at the service layer (task 20.2) - the column
# only stores it.
# ---------------------------------------------------------------------------
class SellerSettings(Base):
    """Single-row, Seller-owned operator settings (Req 19, 6.2/6.6)."""

    __tablename__ = "seller_settings"
    __table_args__ = (
        # Singleton guard mirroring ``meta``'s CHECK (meta_id = 1): the constant
        # discriminator is pinned to 1 and made UNIQUE so only one row exists.
        sa.CheckConstraint("singleton = 1", name="singleton"),
        sa.UniqueConstraint("singleton"),
        # pickup_location is NULL until set; when present it must be 1-500 chars
        # (Req 19.1/19.2).
        sa.CheckConstraint(
            "pickup_location IS NULL OR "
            "(length(pickup_location) >= 1 AND length(pickup_location) <= 500)",
            name="pickup_location_len",
        ),
    )

    seller_settings_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid, primary_key=True, default=uuid.uuid4
    )
    # Constant discriminator pinned to 1 (singleton guard); never user-facing.
    singleton: Mapped[int] = mapped_column(
        sa.SmallInteger, nullable=False, server_default=sa.text("1")
    )
    # Seller-defined collection address; NULL until set (Req 19.1/19.2, 19.9).
    pickup_location: Mapped[Optional[str]] = mapped_column(sa.Text, nullable=True)
    # Payee VPA; NULL until set. VPA shape validated at the service layer.
    upi_address: Mapped[Optional[str]] = mapped_column(sa.Text, nullable=True)
    # Object-storage reference to the uploaded UPI QR image; blob not in DB.
    upi_qr_object_key: Mapped[Optional[str]] = mapped_column(sa.Text, nullable=True)
    # Configured UTR format; default = exactly 12 alphanumeric (Req 6.2/6.6).
    utr_pattern: Mapped[str] = mapped_column(
        sa.Text, nullable=False, server_default=sa.text(f"'{DEFAULT_UTR_PATTERN}'")
    )
    updated_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )
    schema_version: Mapped[int] = mapped_column(
        sa.SmallInteger, nullable=False, server_default=sa.text("1")
    )


