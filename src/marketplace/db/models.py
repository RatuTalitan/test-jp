def _enum(py_enum: type[enum.Enum], name: str) -> sa.Enum:
    """Build a portable :class:`sqlalchemy.Enum` storing the member *values*.

    ``create_constraint=True`` makes SQLite (which has no native ENUM) enforce
    the allowed value set via a CHECK constraint, mirroring the native ENUM
    enforcement PostgreSQL gives for free.
    """
    return sa.Enum(
        py_enum,
        name=name,
        native_enum=True,  # native ENUM on PostgreSQL; VARCHAR+CHECK on SQLite
        create_constraint=True,
        values_callable=lambda e: [m.value for m in e],
    )


def _json() -> sa.types.TypeEngine:
    """Build a portable JSON column type.

    Renders as ``JSONB`` on PostgreSQL (binary, indexable) and as generic
    ``JSON`` (stored as TEXT) on SQLite, per design.md ("use JSONB on Postgres,
    JSON on SQLite"). Used for the audit ``detail`` and notification ``payload``
    documents, both of which embed a ``format_version`` so the payload formats
    stay additively versioned (Req 13.7).
    """
    return sa.JSON().with_variant(postgresql.JSONB(), "postgresql")


