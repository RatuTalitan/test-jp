class Category(Base):
    """Product category with a case-insensitive-unique name (Req 2.8, 2.11)."""

    __tablename__ = "categories"
    __table_args__ = (
        sa.CheckConstraint(
            "length(name) >= 1 AND length(name) <= 50", name="name_len"
        ),
        # Case-insensitive uniqueness via a functional unique index on lower(name).
        sa.Index("uq_categories_name_lower", sa.func.lower(sa.column("name")), unique=True),
    )

    category_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid, primary_key=True, default=uuid.uuid4
    )
    name: Mapped[str] = mapped_column(sa.Text, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )


class Product(Base):
    """Catalog product with range CHECK constraints (Req 2.5, 2.6, 2.9)."""

    __tablename__ = "products"
    __table_args__ = (
        sa.CheckConstraint(
            "length(name) >= 1 AND length(name) <= 100", name="name_len"
        ),
        sa.CheckConstraint(
            "description IS NULL OR length(description) <= 1000",
            name="description_len",
        ),
        sa.CheckConstraint(
            f"price_per_unit >= 0 AND price_per_unit <= {PRICE_MAX}",
            name="price_range",
        ),
        sa.CheckConstraint(
            f"min_order_quantity > 0 AND min_order_quantity <= {QUANTITY_MAX}",
            name="moq_range",
        ),
        sa.CheckConstraint(
            f"stock_quantity >= 0 AND stock_quantity <= {QUANTITY_MAX}",
            name="stock_range",
        ),
        # Defense-in-depth non-negative stock guard (task 3.1 detail / Req 7.4).
        sa.CheckConstraint("stock_quantity >= 0", name="stock_non_negative"),
        # Browsing indexes.
        sa.Index("ix_products_category_id_available", "category_id", "available"),
        sa.Index(
            "ix_products_available_partial",
            "category_id",
            postgresql_where=sa.text("available"),
            sqlite_where=sa.text("available"),
        ),
    )

    product_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid, primary_key=True, default=uuid.uuid4
    )
    name: Mapped[str] = mapped_column(sa.Text, nullable=False)
    category_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid, sa.ForeignKey("categories.category_id"), nullable=False
    )
    description: Mapped[Optional[str]] = mapped_column(sa.Text, nullable=True)
    unit: Mapped[Unit] = mapped_column(_enum(Unit, UNIT_ENUM_NAME), nullable=False)
    price_per_unit: Mapped[float] = mapped_column(sa.Numeric(12, 2), nullable=False)
    min_order_quantity: Mapped[float] = mapped_column(sa.Numeric(12, 3), nullable=False)
    stock_quantity: Mapped[float] = mapped_column(sa.Numeric(12, 3), nullable=False)
    available: Mapped[bool] = mapped_column(
        sa.Boolean, nullable=False, server_default=sa.true()
    )
    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )


