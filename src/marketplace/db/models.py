# ---------------------------------------------------------------------------
# Notifications (task 3.3; design.md -> Data Models -> Notifications; Req 11).
#
# Delivery + bounded-retry queue. Enqueue is idempotent per
# ``(order_id, kind, transition_seq)`` (UNIQUE) so a retried transition never
# produces duplicate notifications (Req 11). The retry worker polls
# ``status IN (PENDING, FAILED) AND next_attempt_at <= now`` ordered by the
# ``(status, next_attempt_at)`` index. ``next_attempt_at`` defaults to now() so
# freshly-enqueued PENDING rows are immediately due. ``payload`` is a
# JSONB/JSON document carrying a ``format_version`` (Req 13.7).
# ---------------------------------------------------------------------------
class Notification(Base):
    """A queued, retry-able customer/Seller notification (Req 11.1-11.5)."""

    __tablename__ = "notifications"
    __table_args__ = (
        # Idempotent enqueue per order/kind/transition (Req 11).
        sa.UniqueConstraint("order_id", "kind", "transition_seq"),
        # Defense-in-depth: the retry budget counter is never negative.
        sa.CheckConstraint("attempts >= 0", name="attempts_non_negative"),
        # Retry-worker poll: due rows by status then schedule.
        sa.Index("ix_notifications_status_next_attempt_at", "status", "next_attempt_at"),
    )

    notification_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid, primary_key=True, default=uuid.uuid4
    )
    order_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid, sa.ForeignKey("orders.order_id"), nullable=False
    )
    recipient_id: Mapped[uuid.UUID] = mapped_column(
        sa.Uuid, sa.ForeignKey("users.user_id"), nullable=False
    )
    kind: Mapped[NotificationKind] = mapped_column(
        _enum(NotificationKind, NOTIFICATION_KIND_ENUM_NAME), nullable=False
    )
    # Monotonic per-order transition counter; part of the idempotency key.
    transition_seq: Mapped[int] = mapped_column(sa.Integer, nullable=False)
    # {format_version, ...} (Req 13.7 additive payload).
    payload: Mapped[dict] = mapped_column(_json(), nullable=False)
    status: Mapped[NotificationStatus] = mapped_column(
        _enum(NotificationStatus, NOTIFICATION_STATUS_ENUM_NAME),
        nullable=False,
        server_default=NotificationStatus.PENDING.value,
    )
    attempts: Mapped[int] = mapped_column(
        sa.SmallInteger, nullable=False, server_default=sa.text("0")
    )
    last_attempt_at: Mapped[Optional[datetime]] = mapped_column(
        sa.DateTime(timezone=True), nullable=True
    )
    # Defaults to now() so a new PENDING row is immediately due for delivery.
    next_attempt_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )
    created_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )
    updated_at: Mapped[datetime] = mapped_column(
        sa.DateTime(timezone=True), nullable=False, server_default=sa.func.now()
    )


