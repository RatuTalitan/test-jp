"""SQLAlchemy 2.0 ORM models / metadata for the marketplace persistence layer.

This module is the **single source of truth for the database schema metadata**
(design.md -> "Stable domain data, versioned at the edges" and "Data Models").
Alembic migrations are wired to :data:`Base.metadata` as their ``target_metadata``
so future migrations (tasks 3.2 / 3.3 / 3.5) can be autogenerated or hand-written
against a consistent picture of the schema.

Task 3.1 establishes the first slice of the schema only:

  * ``meta``        - single-row table holding the ``schema_version`` (Req 13.7).
  * ``users``       - channel-neutral identity, role, offline-payment flag, and
                      the per-user ``language_preference`` (Req 1.6, 17.1, 18.x).
  * ``categories``  - case-insensitive-unique product groups (Req 2.8, 2.11).
  * ``products``    - catalog items with range CHECK constraints (Req 2.5-2.9).

Carts, orders, payments, audit, notifications and seller settings are
intentionally *not* defined here; they arrive in later migrations.

Portability: the models use SQLAlchemy generic types (``Uuid``, ``Numeric``,
``DateTime(timezone=True)``, ``Enum``) that render natively on PostgreSQL
(runtime) and degrade cleanly on SQLite (local/dev/test) - e.g. native ``ENUM``
types on PostgreSQL become ``VARCHAR`` + ``CHECK`` on SQLite, and ``UUID``
becomes ``CHAR(32)``.
"""

from __future__ import annotations

import enum
